import { pipe } from '../../../shared/kernel/pipe.ts';

/** Сколько знаков чужого текста остаётся после чистки: метка — 256, ответ опроса и строка свойства — 500. */
export var TEXT_LIMITS = { label: 256, text: 500 } as const;

/**
 * Чужой текст для показа: тело события хранится как пришло, а при чтении управляющие и невидимые знаки
 * (`\p{C}`) уходят, переводы строк и табуляции становятся пробелами, пробелы схлопываются, длина — до `max`
 * знаков. Экранировать при выводе всё равно нужно.
 */
export var cleanText = (raw: string, max: number): string =>
  pipe(
    (_: string) =>
      _.replace(/\p{C}/gu, (char) => (/\s/u.test(char) ? ' ' : '')),
    (_) => _.replace(/\s+/gu, ' ').trim(),
    (_) => [..._].slice(0, max).join('').trimEnd()
  )(raw);
