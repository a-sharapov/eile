    <section id="admin-code" data-topic hidden={!shown('admin-code')}>
      <h3>Где выполняется код</h3>
      <p>Код шаблонов, компонентов и плагинов выполняется на сервере: посетитель получает готовый HTML. В браузере работает только код островов и скриптов сайта.</p>
      <dl>
        <dt>Компонент</dt>
        <dd>
          Когда код готовит часть страницы: список страниц, расчёт, данные из <code>$core</code>. Он выполняется при рендере, и
          результат попадает в кэш вместе со страницей. Если нужен сам запрос — cookie, параметры адреса, текущее время, —
          поставьте компонент через <code>{'<Uncached name="…"\u00a0/>'}</code> из <code>$core/Uncached</code>: он будет рендериться
          на каждом запросе, а остальная страница останется в кэше.
        </dd>
        <dt>Плагин</dt>
        <dd>
          Когда код должен сработать в определённый момент, а не нарисовать часть страницы: <code>render</code> правит готовый
          HTML любой страницы перед отдачей, <code>notFound</code> отвечает адресом переадресации вместо 404, <code>on</code>
          реагирует на события сайта — например, вызывает вебхук, когда страницу опубликовали.
        </dd>
        <dt>Остров</dt>
        <dd>
          Компонент, который работает в браузере: <code>{'<Island name="…"\u00a0/>'}</code> из <code>$core/Island</code>.
          <code>$core</code> в нём нет — данные сервера он получает через параметры, а их видит посетитель: секреты в них не
          передавайте. Остров можно поставить и внутри компонента из <code>Uncached</code>: тогда параметры считаются на каждом
          запросе — например, цена по коду партнёра из cookie, — а страница вокруг остаётся в кэше.
        </dd>
        <dt>Скрипт</dt>
        <dd>
          Когда в браузере нужен свой JavaScript, а не компонент: сцена Three.js, виджет, аналитика. Скрипт — ES-модуль из
          «Элементов» до 2 МБ. Шаблон подключает его в <code>{'<svelte:head>'}</code> тегом <code>script</code> с адресом
          <code>script('имя')</code>. Импортировать скрипт может только адреса <code>https://</code>: библиотеки соберите в тот же
          файл заранее.
        </dd>
      </dl>
      <p>Компоненты импортируют только <code>svelte</code>, <code>$core</code> и другие компоненты, плагины — только <code>$core</code>.</p>
    </section>
