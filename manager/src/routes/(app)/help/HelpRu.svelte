        <dd>JavaScript для браузера — ES-модули: сцена Three.js, виджет, счётчик. Шаблон подключает скрипт через <code>script('имя')</code>, адрес меняется с каждой правкой, и браузер всегда получает свежую версию.</dd>
        <dt>Плагины</dt>
        <dd>Меняют поведение сайта — например, переадресации. Включаются и выключаются кнопкой сразу.</dd>
